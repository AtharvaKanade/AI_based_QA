"""
AI Test Generator & Defect Analysis Module using Google Gemini.
Translates user stories and acceptance criteria into executable Pytest suites,
and performs automated defect root-cause analysis.
"""

import os
import re
import sys
import argparse
from typing import Optional

PROMPTS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "prompts")
GENERATED_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "generated")


def load_prompt_template(filename: str) -> str:
    path = os.path.join(PROMPTS_DIR, filename)
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def extract_python_code(response_text: str) -> str:
    """Extract python code enclosed in markdown fences, or return raw text."""
    pattern = r"```(?:python)?\s*([\s\S]*?)\s*```"
    match = re.search(pattern, response_text, re.IGNORECASE)
    if match:
        return match.group(1).strip()
    return response_text.strip()


class AIEngine:
    def __init__(self, api_key: Optional[str] = None):
        self.api_key = api_key or os.getenv("GEMINI_API_KEY")
        self.client = None
        self._init_client()

    def _init_client(self):
        if not self.api_key:
            return

        # Attempt to initialize google.genai or google.generativeai
        try:
            from google import genai
            self.client = genai.Client(api_key=self.api_key)
            self._mode = "genai"
        except ImportError:
            try:
                import google.generativeai as gai
                gai.configure(api_key=self.api_key)
                self.client = gai.GenerativeModel("gemini-1.5-flash")
                self._mode = "legacy"
            except ImportError:
                self.client = None

    def generate_tests_from_story(self, user_story: str, output_file: Optional[str] = None) -> str:
        """
        Generate automated Pytest code from a User Story.
        Uses Gemini API when configured; otherwise falls back to deterministic template generation.
        """
        template = load_prompt_template("user_story_prompt.txt")
        prompt = template.replace("{user_story}", user_story)

        generated_code = ""

        if self.client:
            try:
                if self._mode == "genai":
                    response = self.client.models.generate_content(
                        model="gemini-2.5-flash",
                        contents=prompt
                    )
                    generated_code = extract_python_code(response.text)
                else:
                    response = self.client.generate_content(prompt)
                    generated_code = extract_python_code(response.text)
            except Exception as e:
                print(f"[!] Warning: Gemini API call failed ({e}). Falling back to deterministic generator.")
                generated_code = self._fallback_test_generator(user_story)
        else:
            generated_code = self._fallback_test_generator(user_story)

        if output_file:
            os.makedirs(os.path.dirname(os.path.abspath(output_file)), exist_ok=True)
            with open(output_file, "w", encoding="utf-8") as f:
                f.write(generated_code)
            print(f"[+] AI Generated test written to: {output_file}")

        return generated_code

    def analyze_defect(self, failure_log: str) -> str:
        """Analyze a test failure log using AI."""
        template = load_prompt_template("defect_analysis_prompt.txt")
        prompt = template.replace("{failure_log}", failure_log)

        if self.client:
            try:
                if self._mode == "genai":
                    response = self.client.models.generate_content(
                        model="gemini-2.5-flash",
                        contents=prompt
                    )
                    return response.text
                else:
                    response = self.client.generate_content(prompt)
                    return response.text
            except Exception as e:
                return f"[!] AI Defect Analysis failed: {e}\n\n" + self._fallback_defect_analyzer(failure_log)
        else:
            return self._fallback_defect_analyzer(failure_log)

    def _fallback_test_generator(self, user_story: str) -> str:
        """Deterministic generator demonstrating AI pipeline output."""
        return f'''"""
AI-GENERATED TEST SUITE
Source Requirement:
{user_story.strip()}

Generated by: AIEngine (Gemini Automation Pipeline)
"""

import pytest
import requests

@pytest.mark.ai
@pytest.mark.api
def test_ai_generated_product_filter_validation(api_server):
    """
    Given an authenticated user querying product inventory
    When filtering by category 'electronics'
    Then all returned products should belong to 'electronics' category.
    """
    response = requests.get(f"{{api_server}}/api/v1/products?category=electronics")
    assert response.status_code == 200, f"Expected 200 OK, got {{response.status_code}}"
    data = response.json()
    assert "products" in data, "Response payload missing 'products' key"
    for item in data["products"]:
        assert item["category"] == "electronics", f"Item category mismatch: {{item['category']}}"

@pytest.mark.ai
@pytest.mark.api
def test_ai_generated_invalid_login_validation(api_server):
    """
    Given a user attempting login with empty credentials
    When submitting the POST /api/v1/auth/login request
    Then the API should return 400 Bad Request with an error message.
    """
    payload = {{"username": "", "password": ""}}
    response = requests.post(f"{{api_server}}/api/v1/auth/login", json=payload)
    assert response.status_code == 400, f"Expected 400 Bad Request, got {{response.status_code}}"
    assert "error" in response.json(), "Missing error key in error response"
'''

    def _fallback_defect_analyzer(self, failure_log: str) -> str:
        """Deterministic defect analysis report."""
        return f"""=== AI DEFECT ANALYSIS REPORT ===
1. Root Cause Summary:
   Assertion or element locator failure identified in execution trace. Target resource or response schema did not match expectations.

2. Severity & Priority:
   Severity: Medium | Priority: P2 (Functional Defect)

3. Defect Classification:
   Contract / State Mismatch.

4. Recommended Remediation:
   - Validate target system state and test data preconditions in SQLite seed.
   - Verify dynamic timeouts or auto-waiting locators for UI elements.
   - Confirm API endpoint payload compatibility against API specification.
"""


def main():
    parser = argparse.ArgumentParser(description="AI Test Generator CLI for Quality Engineering")
    parser.add_argument("--story", type=str, help="User story or requirement text")
    parser.add_argument("--output", type=str, default=os.path.join(GENERATED_DIR, "test_ai_demo.py"),
                        help="Path to output generated test file")
    parser.add_argument("--defect-log", type=str, help="Failure log for AI defect analysis")

    args = parser.parse_args()
    engine = AIEngine()

    if args.defect_log:
        with open(args.defect_log, "r", encoding="utf-8") as f:
            log_content = f.read()
        report = engine.analyze_defect(log_content)
        print("\n" + report)
    elif args.story:
        code = engine.generate_tests_from_story(args.story, output_file=args.output)
        print("\nGenerated Test Code Preview:\n" + code)
    else:
        # Default run: generate sample demo test
        default_story = (
            "As an online shopper, I want to filter products by category 'electronics' "
            "so that I can quickly find tech accessories without browsing unrelated items."
        )
        print(f"[*] Generating test case for default story:\n    '{default_story}'")
        code = engine.generate_tests_from_story(default_story, output_file=args.output)


if __name__ == "__main__":
    main()

